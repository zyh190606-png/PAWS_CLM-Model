    subroutine linkVdataFromGd(gd_rt)
    ! link data passed in from gd to Vdata structures
    ! Technically, this is not really necessary if we don't use local structures defined in vdata
    ! but it's perhaps more convenient to use original fortran style structures
    ! Codes are generated by Matlab. This is way easier than matRW:
    ! B='Veg';d=g.(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gd_ptr,''',f,''',g%',B,'(1)%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
    ! and then some minor adjustment

    use gd_Mod
    use vdata
    !use ch_assert_mod
    implicit none
    type(gd),target:: gd_rt
    type(gd), pointer:: gdt, gdt2, gdt3
    real*8, pointer:: temp1d(:),temp2d(:,:),temp3d(:,:,:),temp4d(:,:,:,:)
    integer, pointer:: temp1L(:),temp2L(:,:),temp3L(:,:,:),temp4L(:,:,:,:)
    integer n,nP,nP2,nP3,i,j,k

    ! Global access to the passed in GD
    gdVDataRt => gd_rt
    gdG => gd_rt .G. 'g'
    gdW => gd_rt .G. 'w'
    gdR => gd_rt .G. 'r' ! will only get the first one


    gdG => gd_rt .G. 'g'
    temp1d => gdG .F. 't'; g%t => temp1d(1)
    temp1d => gdG .F. 'dt'; g%dt => temp1d(1)
    temp1d => gdG .F. 'status'; g%status => temp1d(1)

    gd_ptr => gdG .G. 'OVN'
    ! B='OVN'; F = fieldnames(g.(B)); for i=1:length(F),f=F{i}; if isnumeric(g.(B).(f)) &&~isempty(g.(B).(f)); disp(['call getptr(gd_ptr,''',f,''',g%',B,'%',f,')']); end; if isstruct(g.(B).(f)), disp(f); end; end
    call getptr(gd_ptr,'h',g%OVN%h)
    call getptr(gd_ptr,'U',g%OVN%U)
    call getptr(gd_ptr,'V',g%OVN%V)
    call getptr(gd_ptr,'S',g%OVN%S)
    call getptr(gd_ptr,'ho',g%OVN%ho)
    call getptr(gd_ptr,'hd',g%OVN%hd)
    call getptr(gd_ptr,'dP',g%OVN%dP)
    call getptr(gd_ptr,'SN',g%OVN%SN)
    call getptr(gd_ptr,'SNSAVE',g%OVN%SNSAVE)
    call getptr(gd_ptr,'prcp',g%OVN%prcp)
    call getptr(gd_ptr,'frac',g%OVN%frac)
    call getptr(gd_ptr,'t',temp1d); g%OVN%t => temp1d(1)
    call getptr(gd_ptr,'dt',temp1d); g%OVN%dt => temp1d(1)
    !call getptr(gd_ptr,'Cond',g%OVN%Cond)
    call getptr(gd_ptr,'Mann',g%OVN%Mann)
    call getptr(gd_ptr,'code',temp1d); g%OVN%Code => temp1d(1)
    call getptr(gd_ptr,'Rf',g%OVN%Rf)
    call getptr(gd_ptr,'Ex',g%OVN%Ex)
    call getptr(gd_ptr,'Qoc',g%OVN%Qoc)
    !call getptr(gd_ptr,'dfrac',g%OVN%dfrac)
    call getptr(gd_ptr,'dist',g%OVN%dist)
    call getptr(gd_ptr,'hc',g%OVN%hc)
    call getptr(gd_ptr,'hf',g%OVN%hf)
    call getptr(gd_ptr,'SATH',g%OVN%SATH)
    call getptr(gd_ptr,'OVF',g%OVN%OVF)
    call getptr(gd_ptr,'ffrac',g%OVN%ffrac)
    call getptr(gd_ptr,'hback',g%OVN%hback)
    call getptr(gd_ptr,'hod',g%OVN%hod)
    call getptr(gd_ptr,'FParm',g%OVN%FParm)
    g%OVN%ms = (/size(g%OVN%h,1),size(g%OVN%h,2)/)

    nP = countRepNum(gd_ptr,'Cond')
    allocate(g%OVN%Cond(nP))
    do i=1,nP
        gdt => gdG .G. 'OVN'
        call getPtr(gdt,'Cond',gdt2,i)
        if (.not. isempty(gdt2,'indices')) then
            call getptr(gdt2,'indices',g%OVN%Cond(i)%idx)  ! name modified
        endif
        if (.not. isempty(gdt2,'type')) then
            call getptr(gdt2,'type',temp1d); g%OVN%Cond(i)%Jtype=int(temp1d(1))
        endif
        if (.not. isempty(gdt2,'BIndexIn1')) call getptr(gdt2,'BIndexIn1',g%OVN%Cond(i)%BIndexIn1)
        if (.not. isempty(gdt2,'BIndexIn2')) call getptr(gdt2,'BIndexIn2',g%OVN%Cond(i)%BIndexIn2)
    enddo


    gd_ptr => gdG .G. 'VDZ'
    ! B='VDZ'; F = fieldnames(g.(B)); for i=1:length(F),f=F{i}; if isnumeric(g.(B).(f)) &&~isempty(g.(B).(f)); disp(['call getptr(gd_ptr,''',f,''',g%',B,'%',f,')']); end; if isstruct(g.(B).(f)), disp(f); end; end

    call getptr(gd_ptr,'DZ',g%VDZ%DZ)
    g%VDZ%m(1)=size(g%VDZ%DZ,1);
    g%VDZ%m(2)=size(g%VDZ%DZ,2);
    g%VDZ%m(3)=size(g%VDZ%DZ,3);
    call getptr(gd_ptr,'DDZ',g%VDZ%DDZ)
    call getptr(gd_ptr,'NZC',g%VDZ%NZC)
    call getptr(gd_ptr,'PRatio',g%VDZ%PRatio)
    call getptr(gd_ptr,'EB',g%VDZ%EB)
    call getptr(gd_ptr,'E',g%VDZ%E)
    call getptr(gd_ptr,'h',g%VDZ%h)
    call getptr(gd_ptr,'ET',g%VDZ%ET)
    call getptr(gd_ptr,'SRC',g%VDZ%SRC)
    call getptr(gd_ptr,'JType',g%VDZ%JType)
    call getptr(gd_ptr,'WTL',g%VDZ%WTL)
    call getptr(gd_ptr,'K',g%VDZ%K)
    call getptr(gd_ptr,'C',g%VDZ%CI) ! name changed
    call getptr(gd_ptr,'THE',g%VDZ%THE)
    call getptr(gd_ptr,'Cond',g%VDZ%Cond)
    call getptr(gd_ptr,'DF',g%VDZ%DF)
    call getptr(gd_ptr,'Dperc',g%VDZ%Dperc)
    call getptr(gd_ptr,'R',g%VDZ%R)
    call getptr(gd_ptr,'t',temp1d); g%VDZ%t => temp1d(1)
    call getptr(gd_ptr,'dt',g%VDZ%dt);
    call getptr(gd_ptr,'dtP',g%VDZ%dtP)
    call getptr(gd_ptr,'STATE',temp1d); g%VDZ%STATE=>temp1d(1)
    call getptr(gd_ptr,'THER',g%VDZ%THER)
    call getptr(gd_ptr,'THES',g%VDZ%THES)
    call getptr(gd_ptr,'KS',g%VDZ%KS)
    call getptr(gd_ptr,'Ko',g%VDZ%Ko)
    call getptr(gd_ptr,'N',g%VDZ%N)
    call getptr(gd_ptr,'LAMBDA',g%VDZ%LAMBDA)
    call getptr(gd_ptr,'ALPHA',g%VDZ%ALPHA)
    call getptr(gd_ptr,'Mapp',g%VDZ%Mapp)
    call getptr(gd_ptr,'FC',g%VDZ%FC)
    call getptr(gd_ptr,'WP',g%VDZ%WP)
    call getptr(gd_ptr,'GWL',g%VDZ%GWL)
    call getptr(gd_ptr,'VParm',g%VDZ%VParm)
    call getptr(gd_ptr,'Sand',g%VDZ%Sand)
    call getptr(gd_ptr,'Clay',g%VDZ%Clay)
    call getptr(gd_ptr,'OM',g%VDZ%OM)
    call getptr(gd_ptr,'ICE',g%VDZ%ICE)
    call getptr(gd_ptr,'soic',g%VDZ%soic)
    call getptr(gd_ptr,'gti',g%VDZ%gti)
    call getptr(gd_ptr,'SMR',g%VDZ%SMR)
    call getptr(gd_ptr,'KSSAVE',g%VDZ%KSSAVE)
    call getptr(gd_ptr,'REP',g%VDZ%REP)
    call getptr(gd_ptr,'SoilMap',g%VDZ%SoilMap)


    gd_ptr => gdG .G. 'VDZ'.G. 'GA'
    ! B='GA';d=g.VDZ.(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gd_ptr,''',f,''',g%VDZ%',B,'%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
    call getptr(gd_ptr,'MM',g%VDZ%GA%MM)
    call getptr(gd_ptr,'SW',g%VDZ%GA%SW)
    call getptr(gd_ptr,'n',g%VDZ%GA%n)
    call getptr(gd_ptr,'l',g%VDZ%GA%l)
    call getptr(gd_ptr,'dn',temp1d); g%VDZ%GA%dn=>temp1d(1)
    call getptr(gd_ptr,'dl',temp1d); g%VDZ%GA%dl=>temp1d(1)
    call getptr(gd_ptr,'hspan',g%VDZ%GA%hspan)
    call getptr(gd_ptr,'nspan',temp1L); g%VDZ%GA%nspan=>temp1L(1)
    call getptr(gd_ptr,'m',g%VDZ%GA%m)
    call getptr(gd_ptr,'h',g%VDZ%GA%h)
    call getptr(gd_ptr,'WFP',g%VDZ%GA%WFP)
    call getptr(gd_ptr,'FM',g%VDZ%GA%FM)
    call getptr(gd_ptr,'KBar',g%VDZ%GA%KBar)
    call getptr(gd_ptr,'Code',g%VDZ%GA%Code)
    call getptr(gd_ptr,'THEW',g%VDZ%GA%THEW)
    call getptr(gd_ptr,'GCode',g%VDZ%GA%GCode)

    allocate(g%VDZ%th)  ! otherwise die upon entrance into getptr
    ! B='th';d=g.VDZ.(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gd_ptr,''',f,''',g%VDZ%',B,'%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
    gd_ptr => gdG .G. 'VDZ'.G. 'th'
    call getptr(gd_ptr,'a',g%VDZ%th%a)
    call getptr(gd_ptr,'c',g%VDZ%th%c)
    call getptr(gd_ptr,'bbase',g%VDZ%th%bbase)
    call getptr(gd_ptr,'Temp',g%VDZ%th%Temp)
    call getptr(gd_ptr,'KT',g%VDZ%th%KT)
    call getptr(gd_ptr,'CT',g%VDZ%th%CT)
    call getptr(gd_ptr,'Sstatev',g%VDZ%th%Sstatev)
    call getptr(gd_ptr,'Ssitev',g%VDZ%th%Ssitev)
    call getptr(gd_ptr,'Soutv',g%VDZ%th%Soutv)
    call getptr(gd_ptr,'tss',g%VDZ%th%tss)
    call getptr(gd_ptr,'tsa',g%VDZ%th%tsa)
    call getptr(gd_ptr,'SParm',g%VDZ%th%SParm)
    call getptr(gd_ptr,'dfc',g%VDZ%th%dfc)
    call getptr(gd_ptr,'SMR',g%VDZ%th%SMR)
    call getptr(gd_ptr,'SNOP',g%VDZ%th%SNOP)
    call getptr(gd_ptr,'SNOE',g%VDZ%th%SNOE)
    call getptr(gd_ptr,'Salb',g%VDZ%th%Salb)
    call getptr(gd_ptr,'BSub',g%VDZ%th%BSub)
    !call getptr(gd_ptr,'state',g%VDZ%th%state)

    nP = countRepNum(gdG,'GW')
    allocate(g%GW(nP))
    do i=1,nP
        call getptr(gdG,'GW',gd_ptr,i)
        ! B='GW';d=g.GW(1); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gd_ptr,''',f,''',g%',B,'(i)%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
        call getptr(gd_ptr,'DZ',g%GW(i)%DZ)
        call getptr(gd_ptr,'EB',g%GW(i)%EB)
        call getptr(gd_ptr,'ES',g%GW(i)%ES)
        call getptr(gd_ptr,'E',g%GW(i)%E)
        call getptr(gd_ptr,'D',g%GW(i)%D)
        call getptr(gd_ptr,'h',g%GW(i)%h)
        call getptr(gd_ptr,'hNew',g%GW(i)%hNew)
        call getptr(gd_ptr,'tt',temp1d); g%GW(i)%tt=>temp1d(1)
        call getptr(gd_ptr,'dt',temp1d); g%GW(i)%dt=>temp1d(1)
        call getptr(gd_ptr,'K',g%GW(i)%K)
        call getptr(gd_ptr,'T',g%GW(i)%T)
        call getptr(gd_ptr,'dd',g%GW(i)%dd)
        call getptr(gd_ptr,'ST',g%GW(i)%ST)
        call getptr(gd_ptr,'W',g%GW(i)%W)
        call getptr(gd_ptr,'W2',g%GW(i)%W2)
        call getptr(gd_ptr,'Seep',g%GW(i)%Seep)
        call getptr(gd_ptr,'DR',g%GW(i)%DR)
        call getptr(gd_ptr,'DLDR',g%GW(i)%DLDR)
        call getptr(gd_ptr,'Qperc',g%GW(i)%Qperc)
        if (i < nP) then
            call getptr(gd_ptr,'botK',g%GW(i)%botK)
            call getptr(gd_ptr,'botD',g%GW(i)%botD)
            call getptr(gd_ptr,'topBound',g%GW(i)%topBound)
        endif
        nP2 = countRepNum(gd_ptr,'Cond')
        if (nP2 > 0) then
            allocate(g%GW(i)%Cond(nP2))
            DO j = 1,nP2
                call getptr(gd_ptr,'Cond',gdt,j)
                ! B='Cond';d=g.GW(1).(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gdt,''',f,''',g%GW(i)%',B,'%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
                call getptr(gdt,'indices',g%GW(i)%Cond(J)%idx) ! name changed
                call getptr(gdt,'type',temp1L); g%GW(i)%Cond(J)%Jtype = temp1L(1)
                if (.not. isempty(gdt,'Cidx')) call getptr(gdt,'Cidx',g%GW(i)%Cond(J)%Cidx)
                if (.not. isempty(gdt,'Sidx')) call getptr(gdt,'Sidx',g%GW(i)%Cond(J)%Sidx)
                if (.not. isempty(gdt,'Nidx')) call getptr(gdt,'Nidx',g%GW(i)%Cond(J)%Nidx)
                if (.not. isempty(gdt,'Widx')) call getptr(gdt,'Widx',g%GW(i)%Cond(J)%Widx)
                if (.not. isempty(gdt,'Eidx')) call getptr(gdt,'Eidx',g%GW(i)%Cond(J)%Eidx)
                if (.not. isempty(gdt,'K')) call getptr(gdt,'K',g%GW(i)%Cond(J)%K)
                if (.not. isempty(gdt,'h')) call getptr(gdt,'h',g%GW(i)%Cond(J)%h)
                if (.not. isempty(gdt,'D')) call getptr(gdt,'D',g%GW(i)%Cond(J)%D)
                if (.not. isempty(gdt,'bnd')) then
                    call getptr(gdt,'bnd',temp1L);
                    g%GW(i)%Cond(J)%bnd = temp1L(1)
                endif
            ENDDO
        endif
        g%GW(i)%ny = size(g%GW(i)%h,1)   !! ADDED
        g%GW(i)%nx = size(g%GW(i)%h,2)
        g%GW(i)%nc = nP2

        !call getptr(gd_ptr,'mH',g%GW(i)%mH)
        !call getptr(gd_ptr,'mB',g%GW(i)%mB)
        !call getptr(gd_ptr,'mK',g%GW(i)%mK)

        !call getptr(gd_ptr,'A1B',g%GW(i)%A1B)
        !call getptr(gd_ptr,'A2',g%GW(i)%A2)
        !call getptr(gd_ptr,'A3',g%GW(i)%A3)
        !call getptr(gd_ptr,'A4',g%GW(i)%A4)
        !call getptr(gd_ptr,'A5',g%GW(i)%A5)

        call getptr(gd_ptr,'STATE',temp1d) ;g%GW(i)%STATE => temp1d(1)
        call getptr(gd_ptr,'MAPP',g%GW(i)%MAPP)
        call getptr(gd_ptr,'STO',g%GW(i)%STO)
        call getptr(gd_ptr,'NLC',g%GW(i)%NLC)
    enddo

    gd_ptr => gdG .G. 'Topo'
    ! B='Topo';d=g.(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gd_ptr,''',f,''',g%',B,'(1)%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
    call getptr(gd_ptr,'E',g%Topo%E)
    call getptr(gd_ptr,'Ex',g%Topo%Ex)
    call getptr(gd_ptr,'Ey',g%Topo%Ey)
    call getptr(gd_ptr,'S0',g%Topo%S0)
    call getptr(gd_ptr,'S0x',g%Topo%S0x)
    call getptr(gd_ptr,'S0y',g%Topo%S0y)
    call getptr(gd_ptr,'S0p',temp1d) ;g%Topo%S0p => temp1d(1)

    gd_ptr => gdG .G. 'Veg'
    ! B='Veg';d=g.(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gd_ptr,''',f,''',g%',B,'%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
    call getptr(gd_ptr,'ny',temp1d); g%Veg%ny = temp1d(1)
    call getptr(gd_ptr,'nx',temp1d); g%Veg%nx = temp1d(1)
    call getptr(gd_ptr,'nt',temp1d); g%Veg%nt = temp1d(1)
    call getptr(gd_ptr,'t',temp1d); g%Veg%t => temp1d(1)
    call getptr(gd_ptr,'dt',temp1d); g%Veg%dt => temp1d(1)
    call getptr(gd_ptr,'Frac',g%Veg%Frac)
    call getptr(gd_ptr,'LAI',g%Veg%LAI)
    call getptr(gd_ptr,'RPT',g%Veg%RPT)
    call getptr(gd_ptr,'BSoil',g%Veg%BSoil)
    call getptr(gd_ptr,'Root',g%Veg%Root)
    call getptr(gd_ptr,'RDFN',g%Veg%RDFN)
