    call getptr(gd_ptr,'Imp',g%Veg%Imp)
    call getptr(gd_ptr,'SWE',g%Veg%SWE)
    call getptr(gd_ptr,'Gprcp',g%Veg%Gprcp)
    call getptr(gd_ptr,'EvapG',g%Veg%EvapG)
    call getptr(gd_ptr,'Salb',g%Veg%Salb)
    call getptr(gd_ptr,'SNOCOV',g%Veg%SNOCOV)
    call getptr(gd_ptr,'SNOCoef',g%Veg%SNOCoef)
    call getptr(gd_ptr,'SNOM',g%Veg%SNOM)
    call getptr(gd_ptr,'NewS',g%Veg%NewS)
    call getptr(gd_ptr,'Evap',g%Veg%Evap)
