    call getptr(gd_ptr,'LUidx',g%Veg%LUidx)
    call getptr(gd_ptr,'hI',g%Veg%hI)
    call getptr(gd_ptr,'day',gdt)
    ! B='day';d=g.Veg.(B); F = fieldnames(d); for i=1:length(F),f=F{i}; if isnumeric(d.(f)) &&~isempty(d.(f)); disp(['call getptr(gdt,''',f,''',g%Veg%',B,'%',f,')']); end; if isstruct(d.(f)), disp(f); end; end
